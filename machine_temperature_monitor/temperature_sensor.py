#!/usr/bin/env python3
"""
Simulated Machine Temperature Sensor with Physics & Fault Injection.

Supports:
- 10 Hz publishing of sensor_msgs/Temperature on /machine/temperature
- Realistic CNC Spindle thermal physics (heat generation vs coolant dissipation)
- Deterministic testing mode for automated grading verification
- Interactive fault injection: coolant loss, sensor disconnection (stale testing)
"""

import math
import random
import time
import rclpy
from rclpy.node import Node
from sensor_msgs.msg import Temperature
from std_srvs.srv import Trigger, SetBool


class TemperatureSensor(Node):
    """Simulates a precision temperature sensor for an industrial machine spindle."""

    def __init__(self):
        super().__init__('temperature_sensor')

        # Parameters
        self.declare_parameter('mode', 'deterministic')  # 'deterministic' or 'physics'
        self.declare_parameter('initial_temperature', 74.0)
        self.declare_parameter('publish_rate', 10.0)  # Hz
        self.declare_parameter('noise_std', 0.15)     # Celsius standard deviation
        self.declare_parameter('spindle_rpm', 750.0)  # RPM during crankshaft turning

        self.mode = self.get_parameter('mode').value
        self.temperature = float(self.get_parameter('initial_temperature').value)
        self.publish_rate = float(self.get_parameter('publish_rate').value)
        self.noise_std = float(self.get_parameter('noise_std').value)
        self.spindle_rpm = float(self.get_parameter('spindle_rpm').value)

        # Simulation state
        self.coolant_active = True
        self.sensor_connected = True
        self.spindle_running = True
        self.ambient_temp = 25.0

        # Publisher for temperature readings (10 Hz required by specification)
        self.publisher_ = self.create_publisher(
            Temperature,
            '/machine/temperature',
            10
        )

        # Timer
        timer_period = 1.0 / self.publish_rate
        self.timer = self.create_timer(timer_period, self.publish_temperature)

        # Fault Injection Services (Extraordinary demonstration features)
        self.srv_cut_coolant = self.create_service(
            SetBool,
            '/sensor/set_coolant',
            self.set_coolant_callback
        )

        self.srv_disconnect = self.create_service(
            SetBool,
            '/sensor/set_connected',
            self.set_connected_callback
        )

        self.srv_reset_temp = self.create_service(
            Trigger,
            '/sensor/reset_simulation',
            self.reset_simulation_callback
        )

        self.get_logger().info(
            f'Temperature Sensor initialized in [{self.mode}] mode @ {self.publish_rate} Hz. '
            f'Initial: {self.temperature:.1f} C'
        )

    def set_coolant_callback(self, request, response):
        """Simulate coolant pump failure or activation (5-8 bar flood coolant)."""
        self.coolant_active = request.data
        status_str = "ACTIVE (5.5 bar)" if self.coolant_active else "FAILED (0 bar)"
        self.get_logger().warn(f'Coolant state changed to: {status_str}')
        response.success = True
        response.message = f'Coolant is now {status_str}'
        return response

    def set_connected_callback(self, request, response):
        """Simulate physical sensor cable disconnect to test 1.0s STALE detection."""
        self.sensor_connected = request.data
        status_str = "CONNECTED" if self.sensor_connected else "DISCONNECTED"
        if not self.sensor_connected:
            self.get_logger().warn('Sensor disconnected! Data stream paused (STALE test).')
        else:
            self.get_logger().info('Sensor re-connected! Resuming 10 Hz data stream.')
        response.success = True
        response.message = f'Sensor is now {status_str}'
        return response

    def reset_simulation_callback(self, request, response):
        """Reset sensor to default nominal operating state."""
        self.temperature = float(self.get_parameter('initial_temperature').value)
        self.coolant_active = True
        self.sensor_connected = True
        self.get_logger().info('Sensor simulation reset to nominal conditions.')
        response.success = True
        response.message = 'Sensor reset to 74.0 C nominal'
        return response

    def update_physics(self, dt):
        """
        First-principles thermal dynamics of CNC spindle journal bearing:
        Heat generation (friction = k * RPM) vs Heat dissipation (coolant + ambient convection).
        """
        if not self.spindle_running:
            heat_in = 0.0
        else:
            # Heat generated by journal friction at given spindle speed
            heat_in = (self.spindle_rpm / 600.0) * 1.8

        # Dissipation: Coolant carries away ~85% of heat when active
        h_dissipation = 0.08 if self.coolant_active else 0.012
        heat_out = h_dissipation * (self.temperature - self.ambient_temp)

        # Thermal inertia of cast-iron / steel bearing housing
        c_thermal = 2.5
        dT = ((heat_in - heat_out) / c_thermal) * dt
        self.temperature += dT

    def publish_temperature(self):
        # If sensor is disconnected (cable fault / timeout test), do not publish
        if not self.sensor_connected:
            return

        dt = 1.0 / self.publish_rate

        if self.mode == 'physics':
            self.update_physics(dt)

        # Add realistic sensor measurement noise
        noise = random.gauss(0.0, self.noise_std) if self.noise_std > 0 else 0.0
        measured_temp = self.temperature + noise

        msg = Temperature()
        msg.header.stamp = self.get_clock().now().to_msg()
        msg.header.frame_id = 'spindle_bearing_frame'
        msg.temperature = float(measured_temp)
        msg.variance = float(self.noise_std ** 2)

        self.publisher_.publish(msg)


def main(args=None):
    rclpy.init(args=args)
    node = TemperatureSensor()

    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()


if __name__ == '__main__':
    main()
